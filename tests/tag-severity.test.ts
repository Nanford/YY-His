describe("tagSeverity", () => {
  it("显式配置的编码都在 02 表内且不重复", () => {
    expect(CONFIGURED_SEVERITY_CODES.filter((code) => !tagV2ByCode.has(code))).toEqual([]);
    expect(new Set(CONFIGURED_SEVERITY_CODES).size).toBe(CONFIGURED_SEVERITY_CODES.length);
  });

  it("02 表全部标签的异常清单与预期完全一致", () => {
    const abnormal = resultTagsV2
      .filter((tag) => tagSeverity(tag.code, tag.name) === "abnormal")
      .map((tag) => tag.code);
    expect(abnormal).toEqual(EXPECTED_ABNORMAL_CODES);
  });

  it("占位标签一律不算异常", () => {
    const placeholders = resultTagsV2.filter((tag) => tag.placeholder);
    expect(placeholders.length).toBeGreaterThan(0);
    for (const tag of placeholders) expect(tagSeverity(tag.code, tag.name)).toBe("info");
  });

  it("正常档、记录性标签、异常标签分别归类", () => {
    expect(tagSeverity("FRAIL_NONE", "无衰弱")).toBe("normal");
    expect(tagSeverity("TCM_BALANCED_BASICALLY", "平和质")).toBe("normal");
    expect(tagSeverity("TCM_BALANCED_NO", "平和质：否")).toBe("info");
    expect(tagSeverity("STOOL_FORM_TYPE_4", "粪便性状4型")).toBe("info");
    expect(isAbnormalTag({ code: "FRAIL_PREFRAIL", tag: "衰弱前期" })).toBe(true);
    expect(isAbnormalTag({ code: "TCM_YIN_DEFICIENCY_TENDENCY", tag: "阴虚质" })).toBe(true);
  });

  it("历史快照里不在 02 表的编码按标签名兜底", () => {
    expect(tagSeverity("LEGACY_FALL", "跌倒风险筛查阳性")).toBe("abnormal");
    expect(tagSeverity("LEGACY_FALL", "跌倒风险筛查阴性")).toBe("normal");
    expect(tagSeverity("LEGACY_X", "其他记录")).toBe("info");
  });
});
